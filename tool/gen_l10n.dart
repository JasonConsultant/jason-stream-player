// Erzeugt lib/l10n/translations.g.dart aus lib/l10n/arb/app_*.arb.
//
//   dart run tool/gen_l10n.dart
//
// app_de.arb ist die Quelle (deutscher Quelltext), app_en.arb/app_tr.arb
// enthalten die Übersetzungen unter denselben Schlüsseln. Bricht mit
// Exit-Code 1 ab, wenn ein Schlüssel fehlt oder Platzhalter abweichen.
import 'dart:convert';
import 'dart:io';

const arbDir = 'lib/l10n/arb';
const outFile = 'lib/l10n/translations.g.dart';
const targetLangs = ['en', 'tr'];

class L10nGenError implements Exception {
  final List<String> problems;
  L10nGenError(this.problems);
  @override
  String toString() => problems.join('\n');
}

final _placeholder = RegExp(r'\{(\d+)\}');

Set<String> placeholdersOf(String s) =>
    _placeholder.allMatches(s).map((m) => m.group(1)!).toSet();

/// Nur die Übersetzungseinträge (ohne `@@locale` und `@key`-Metadaten).
Map<String, String> arbMessages(Map<String, dynamic> arb) => {
      for (final e in arb.entries)
        if (!e.key.startsWith('@')) e.key: e.value as String,
    };

Map<String, dynamic> readArb(String lang, {String dir = arbDir}) {
  final f = File('$dir/app_$lang.arb');
  if (!f.existsSync()) throw L10nGenError(['${f.path} fehlt.']);
  return jsonDecode(f.readAsStringSync()) as Map<String, dynamic>;
}

/// Prüft die ARB-Dateien und liefert den Inhalt von translations.g.dart.
String generate(Map<String, dynamic> deArb, Map<String, Map<String, dynamic>> targets) {
  final problems = <String>[];
  final de = arbMessages(deArb);
  final seen = <String, String>{};
  for (final e in de.entries) {
    final prev = seen[e.value];
    if (prev != null) {
      problems.add('app_de.arb: "${e.key}" und "$prev" haben denselben Text.');
    }
    seen[e.value] = e.key;
    final ph = placeholdersOf(e.value);
    if (ph.isNotEmpty) {
      final meta = deArb['@${e.key}'];
      final declared = meta is Map && meta['placeholders'] is Map
          ? (meta['placeholders'] as Map).keys.cast<String>().toSet()
          : <String>{};
      if (declared.length != ph.length || !declared.containsAll(ph)) {
        problems.add('app_de.arb: "@${e.key}" muss die Platzhalter '
            '${ph.toList()..sort()} auflisten.');
      }
    }
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_l10n.dart – DO NOT EDIT.')
    ..writeln('// Edit lib/l10n/arb/*.arb instead and run '
        '`dart run tool/gen_l10n.dart`.')
    ..writeln('// Schlüssel = deutscher Quelltext aus app_de.arb.')
    ..writeln()
    ..writeln('const Map<String, Map<String, String>> translations = {');
  for (final lang in targetLangs) {
    final arb = targets[lang];
    if (arb == null) {
      problems.add('app_$lang.arb fehlt.');
      continue;
    }
    final msgs = arbMessages(arb);
    for (final k in msgs.keys) {
      if (!de.containsKey(k)) {
        problems.add('app_$lang.arb: Schlüssel "$k" gibt es nicht in app_de.arb.');
      }
    }
    out.writeln("  '$lang': {");
    for (final e in de.entries) {
      final v = msgs[e.key];
      if (v == null || v.isEmpty) {
        problems.add('app_$lang.arb: Schlüssel "${e.key}" fehlt.');
        continue;
      }
      final a = placeholdersOf(e.value), b = placeholdersOf(v);
      if (a.length != b.length || !a.containsAll(b)) {
        problems.add('app_$lang.arb: "${e.key}" hat Platzhalter '
            '${b.toList()..sort()}, erwartet ${a.toList()..sort()}.');
      }
      out.writeln('    ${dartString(e.value)}:\n        ${dartString(v)},');
    }
    out.writeln('  },');
  }
  out.writeln('};');
  if (problems.isNotEmpty) throw L10nGenError(problems);
  return out.toString();
}

String dartString(String s) {
  final esc = s
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r')
      .replaceAll('\t', r'\t');
  return "'$esc'";
}

/// Liest die ARB-Dateien und erzeugt den Dateiinhalt (für Tests).
String generateFromDisk({String dir = arbDir}) => generate(
    readArb('de', dir: dir),
    {for (final l in targetLangs) l: readArb(l, dir: dir)});

void main() {
  try {
    final code = generateFromDisk();
    File(outFile).writeAsStringSync(code);
    stdout.writeln('$outFile geschrieben.');
  } on L10nGenError catch (e) {
    stderr.writeln('gen_l10n: Fehler in den ARB-Dateien:\n$e');
    exitCode = 1;
  } on FormatException catch (e) {
    stderr.writeln('gen_l10n: ARB-Datei ist kein gültiges JSON: $e');
    exitCode = 1;
  }
}
